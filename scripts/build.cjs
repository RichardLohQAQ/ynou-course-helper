const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const { zipSync, unzipSync } = require('fflate');
require('./check.cjs');
const root = path.resolve(__dirname, '..');
const files = require('./files.cjs');
const { version } = require('../package.json');
const archive = {};
for (const name of files) archive[name] = fs.readFileSync(path.join(root, 'extension', name));
archive['LICENSE'] = fs.readFileSync(path.join(root, 'LICENSE'));
archive['安装说明.txt'] = Buffer.from('云开课程助手 ' + version + '\n\n解压到固定文件夹，在 Chrome / Edge 扩展管理页开启开发者模式，点击“加载已解压的扩展程序”，选择包含 manifest.json 的此文件夹。\n登录教学平台并刷新页面，再打开助手扫描课程。\n网上作业需要先配置自己的 API 地址、API Key 和模型。无内置密钥。\n更新前停止任务；替换文件后重新加载扩展并刷新平台页面。\n', 'utf8');
const zip = zipSync(archive, { level: 9, mtime: new Date('2026-01-01T00:00:00Z') });
const extracted = unzipSync(zip);
assert.deepEqual(Object.keys(extracted).sort(), Object.keys(archive).sort());
for (const name of Object.keys(archive)) assert.ok(Buffer.from(extracted[name]).equals(Buffer.from(archive[name])), 'Archive mismatch: ' + name);
const output = path.join(root, 'dist');
fs.mkdirSync(output, { recursive: true });
const name = `ynou-course-helper-${version}.zip`;
fs.writeFileSync(path.join(output, name), zip);
fs.writeFileSync(path.join(output, 'SHA256SUMS.txt'), createHash('sha256').update(zip).digest('hex') + '  ' + name + '\n');
console.log(`Built dist/${name} (${zip.length} bytes, ${Object.keys(archive).length} verified files).`);
